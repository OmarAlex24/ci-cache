#!/usr/bin/env bash
# Sets up the CI cache in a Boat sandbox: requests a session from the Worker with the
# sandbox key and the current git branch, and writes the exports to ~/.ci-cache.env.
#
#   CI_CACHE_URL=https://ci-cache.<account>.workers.dev \
#   CI_CACHE_SANDBOX_KEY=sk_... \
#   bash ci-cache-env.sh [repo directory]      # defaults to the current one
#   source ~/.ci-cache.env
#
# Optional variables:
#   CI_CACHE_BRANCH    branch to use (if HEAD is detached or you want another one)
#   CI_CACHE_ENV_FILE  where to write the exports (default ~/.ci-cache.env)
#
# A sandbox key always gets the branch tier (`rama`): what is written here never reaches main/.
# Never prints the key or the token.
set -euo pipefail

fail() {
  echo "ci-cache: $*" >&2
  exit 1
}

# Text field of a flat JSON object. jq if available; otherwise sed (the Worker's response
# is compact JSON and its values contain no escaped quotes).
json_field() {
  local field=$1 file=$2
  if command -v jq >/dev/null 2>&1; then
    jq -r --arg f "$field" '.[$f] // empty' "$file"
  else
    sed -n "s/.*\"$field\":\"\\([^\"]*\\)\".*/\\1/p" "$file"
  fi
}

url=${CI_CACHE_URL:-}
key=${CI_CACHE_SANDBOX_KEY:-}
dir=${1:-.}
env_file=${CI_CACHE_ENV_FILE:-$HOME/.ci-cache.env}

[[ -n $url ]] || fail "CI_CACHE_URL is not set"
[[ -n $key ]] || fail "CI_CACHE_SANDBOX_KEY is not set"
[[ $key == sk_* ]] || fail "CI_CACHE_SANDBOX_KEY does not look like a sandbox key (sk_...)"
url=${url%/}

branch=${CI_CACHE_BRANCH:-}
if [[ -z $branch ]]; then
  branch=$(git -C "$dir" symbolic-ref --quiet --short HEAD) ||
    fail "HEAD is detached in $dir: check out a branch or set CI_CACHE_BRANCH"
fi
# git doesn't allow \ or control characters in branch names; only quotes need escaping.
body="{\"branch\":\"${branch//\"/\\\"}\"}"

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
# The key goes through stdin (-H @-) so it doesn't show up in the process list.
status=$(printf 'Authorization: Bearer %s\n' "$key" | curl -sS --retry 3 -X POST \
  -H @- -H 'content-type: application/json' --data "$body" \
  -o "$tmp" -w '%{http_code}' "$url/v1/session") || fail "could not reach $url"
if [[ $status != 200 ]]; then
  fail "POST /v1/session answered $status: $(json_field message "$tmp")"
fi

token=$(json_field token "$tmp")
tier=$(json_field tier "$tmp")
repo=$(json_field repo "$tmp")
expires=$(json_field expiresAt "$tmp")
[[ -n $token && -n $repo ]] || fail "unexpected session response"

umask 077
{
  echo "# Generated by ci-cache-env.sh: $tier session for branch $branch until $expires"
  echo "export TURBO_API='$url'"
  echo "export TURBO_TOKEN='$token'"
  echo "export TURBO_TEAM='${repo#*/}'"
  echo "export SCCACHE_WEBDAV_ENDPOINT='$url/dav'"
  echo "export SCCACHE_WEBDAV_TOKEN='$token'"
  # R2 has no directories: without this sccache sends a PROPFIND before every PUT.
  echo "export SCCACHE_WEBDAV_DISABLE_CREATE_DIR=true"
  echo "export CARGO_INCREMENTAL=0"
  if command -v sccache >/dev/null 2>&1; then echo "export RUSTC_WRAPPER=sccache"; fi
} >"$env_file"
chmod 600 "$env_file"

# The sccache server keeps the environment it started with: restart it so it picks up
# the new token on the next build.
if command -v sccache >/dev/null 2>&1; then sccache --stop-server >/dev/null 2>&1 || true; fi

echo "ci-cache: $tier session for branch '$branch' ($repo) until $expires"
echo "ci-cache: exports in $env_file — load them with: source $env_file"
