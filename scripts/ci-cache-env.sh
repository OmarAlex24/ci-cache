#!/usr/bin/env bash
# Sets up the CI cache in a sandbox (any machine where an agent builds, with a sandbox key):
# requests a session from the Worker with the sandbox key and the current git branch, and
# writes the exports to ~/.ci-cache.env.
#
#   CI_CACHE_URL=https://ci-cache.<your-subdomain>.workers.dev \
#   CI_CACHE_SANDBOX_KEY=sk_... \
#   bash ci-cache-env.sh [repo directory]      # defaults to the current one
#   source ~/.ci-cache.env                     # in every shell that builds
#
# Sourcing ~/.ci-cache.env renews the session first, by running this script again, when
# the repo's branch changed (`git switch`) or the token expires within 15 minutes. That
# needs CI_CACHE_SANDBOX_KEY (and CI_CACHE_URL, or the one recorded) in the environment and
# this script where it ran. If the renewal fails, `source` says why, unsets the session
# variables and returns 1: builds then run without the remote cache, never on the old
# branch's session. CI_CACHE_NO_REFRESH=1 turns the renewal off. The file never holds the key.
#
# Optional variables:
#   CI_CACHE_BRANCH    branch to use (if HEAD is detached or you want another one); the
#                      file then keeps that branch and only renews on expiry
#   CI_CACHE_ENV_FILE  where to write the exports (default ~/.ci-cache.env)
#   CI_CACHE_FINGERPRINT=false  don't upload the cache fingerprint (see below)
#   CI_CACHE_FINGERPRINT_SCRIPT path to cache-fingerprint.sh (default: next to this script)
#
# After the session it runs cache-fingerprint.sh in the checkout, with the exports loaded,
# and uploads it (PUT /v1/fingerprint) so the branch's CI can compare it with its own and
# warn about the exact line that makes the cache miss. A failed upload is a warning: the
# exports are already written and the script still succeeds.
#
# A sandbox key always gets the branch tier (`rama`): what is written here never reaches main/.
# Never prints the key or the token.
set -euo pipefail

fail() {
  echo "ci-cache: $*" >&2
  exit 1
}

warn() {
  echo "ci-cache: warning: $*" >&2
}

# Text field of a flat JSON object. jq if available; otherwise sed (the Worker's response
# is compact JSON and its values contain no escaped quotes).
json_field() {
  local field=$1 file=$2
  if command -v jq >/dev/null 2>&1; then
    jq -r --arg f "$field" '.[$f] // empty' "$file"
  else
    sed -n "s/.*\"$field\":\"\\([^\"]*\\)\".*/\\1/p" "$file"
  fi
}

url=${CI_CACHE_URL:-}
key=${CI_CACHE_SANDBOX_KEY:-}
dir=${1:-.}
env_file=${CI_CACHE_ENV_FILE:-$HOME/.ci-cache.env}

[[ -n $url ]] || fail "CI_CACHE_URL is not set"
[[ -n $key ]] || fail "CI_CACHE_SANDBOX_KEY is not set"
[[ $key == sk_* ]] || fail "CI_CACHE_SANDBOX_KEY does not look like a sandbox key (sk_...)"
url=${url%/}

branch=${CI_CACHE_BRANCH:-}
pinned=0
if [[ -n $branch ]]; then pinned=1; fi
if [[ -z $branch ]]; then
  branch=$(git -C "$dir" symbolic-ref --quiet --short HEAD) ||
    fail "HEAD is detached in $dir: check out a branch or set CI_CACHE_BRANCH"
fi
# git doesn't allow \ or control characters in branch names; only quotes need escaping.
body="{\"branch\":\"${branch//\"/\\\"}\"}"

tmp=$(mktemp)
fp=$(mktemp)
new_env=""
trap 'rm -f "$tmp" "$fp" ${new_env:+"$new_env"}' EXIT
# The key goes through stdin (-H @-) so it doesn't show up in the process list.
status=$(printf 'Authorization: Bearer %s\n' "$key" | curl -sS --retry 3 -X POST \
  -H @- -H 'content-type: application/json' --data "$body" \
  -o "$tmp" -w '%{http_code}' "$url/v1/session") || fail "could not reach $url"
if [[ $status != 200 ]]; then
  fail "POST /v1/session answered $status: $(json_field message "$tmp")"
fi

token=$(json_field token "$tmp")
tier=$(json_field tier "$tmp")
repo=$(json_field repo "$tmp")
expires=$(json_field expiresAt "$tmp")
[[ -n $token && -n $repo ]] || fail "unexpected session response"

# For the renewal check in the env file: where this ran, as absolute paths.
dir_abs=$(cd "$dir" && pwd -P) || fail "no directory $dir"
self=${BASH_SOURCE[0]}
case $self in */*) ;; *) self=./$self ;; esac
self=$(cd "${self%/*}" && pwd -P)/${self##*/}
case $env_file in /*) ;; *) env_file=$PWD/$env_file ;; esac
# The expiry as epoch seconds: GNU date, BSD date, or 0 (unknown: no expiry check).
exp_epoch=$(date -u -d "$expires" +%s 2>/dev/null ||
  date -u -j -f '%Y-%m-%dT%H:%M:%S' "${expires%%.*}" +%s 2>/dev/null || echo 0)
[[ $exp_epoch =~ ^[0-9]+$ ]] || exp_epoch=0
# A value inside single quotes in the env file.
sq() { printf "'%s'" "${1//\'/\'\\\'\'}"; }

umask 077
# Written next to the old file and renamed over it: a shell that is sourcing the old one
# (the renewal runs from inside it) keeps reading a complete file.
new_env=$(mktemp "$env_file.XXXXXX") || fail "can't write next to $env_file"
{
  echo "# Generated by ci-cache-env.sh: $tier session for branch $branch until $expires"
  echo "# Source it in every shell that builds. It renews the session first (by running"
  echo "# ci-cache-env.sh again) when the branch changed or the token expires within 15 min."
  echo "_cce_dir=$(sq "$dir_abs") _cce_branch=$(sq "$branch") _cce_pinned=$pinned _cce_exp=$exp_epoch"
  echo "_cce_script=$(sq "$self") _cce_file=$(sq "$env_file") _cce_url=$(sq "$url") _cce_why="
  # The renewal check, literally (no expansion here: it runs when the file is sourced).
  # POSIX sh, and safe under set -eu, in bash, zsh and dash.
  IFS= read -r -d '' renew <<'RENEW' || true
if [ -z "${_CI_CACHE_SOURCING:-}" ] && [ "${CI_CACHE_NO_REFRESH:-}" != 1 ]; then
  if [ "$_cce_pinned" = 0 ] && [ -d "$_cce_dir" ] && command -v git >/dev/null 2>&1; then
    _cce_now=$(git -C "$_cce_dir" symbolic-ref --quiet --short HEAD 2>/dev/null) || _cce_now=
    if [ -n "$_cce_now" ] && [ "$_cce_now" != "$_cce_branch" ]; then
      _cce_why="$_cce_dir is now on branch $_cce_now, not $_cce_branch"
    fi
  fi
  if [ -z "$_cce_why" ] && [ "$_cce_exp" -gt 0 ] && command -v date >/dev/null 2>&1; then
    _cce_now=$(date +%s 2>/dev/null) || _cce_now=0
    if [ "$_cce_now" -ge $((_cce_exp - 900)) ]; then _cce_why="the session expires within 15 minutes"; fi
  fi
fi
if [ -n "$_cce_why" ]; then
  echo "ci-cache: renewing the session: $_cce_why" >&2
  _cce_pin=
  if [ "$_cce_pinned" = 1 ]; then _cce_pin=$_cce_branch; fi
  if [ -r "$_cce_script" ] && CI_CACHE_URL="${CI_CACHE_URL:-$_cce_url}" CI_CACHE_ENV_FILE="$_cce_file"     CI_CACHE_BRANCH="$_cce_pin" bash "$_cce_script" "$_cce_dir" >&2; then
    _CI_CACHE_SOURCING=1
    . "$_cce_file"
    unset _CI_CACHE_SOURCING
    return 0
  fi
  echo "ci-cache: could not renew the session (see above), so this shell has no ci-cache session:" >&2
  echo "ci-cache: builds won't use the remote cache. Fix it, then: bash $_cce_script $_cce_dir && . $_cce_file" >&2
  unset TURBO_API TURBO_TOKEN TURBO_TEAM SCCACHE_WEBDAV_ENDPOINT SCCACHE_WEBDAV_TOKEN
  if command -v sccache >/dev/null 2>&1; then sccache --stop-server >/dev/null 2>&1 || :; fi
  unset _cce_dir _cce_branch _cce_pinned _cce_exp _cce_script _cce_file _cce_url _cce_why _cce_now _cce_pin
  return 1
fi
unset _cce_dir _cce_branch _cce_pinned _cce_exp _cce_script _cce_file _cce_url _cce_why _cce_now _cce_pin
RENEW
  printf '%s' "$renew"
  echo "export TURBO_API='$url'"
  echo "export TURBO_TOKEN='$token'"
  echo "export TURBO_TEAM='${repo#*/}'"
  echo "export SCCACHE_WEBDAV_ENDPOINT='$url/dav'"
  echo "export SCCACHE_WEBDAV_TOKEN='$token'"
  # R2 has no directories: without this sccache sends a PROPFIND before every PUT.
  echo "export SCCACHE_WEBDAV_DISABLE_CREATE_DIR=true"
  echo "export CARGO_INCREMENTAL=0"
  if command -v sccache >/dev/null 2>&1; then echo "export RUSTC_WRAPPER=sccache"; fi
} >"$new_env"
chmod 600 "$new_env"
mv -f "$new_env" "$env_file"
new_env=""

# The sccache server keeps the environment it started with: restart it so it picks up
# the new token on the next build.
if command -v sccache >/dev/null 2>&1; then sccache --stop-server >/dev/null 2>&1 || true; fi

# Best effort from here on: the session and the exports are done.
upload_fingerprint() {
  local script=${CI_CACHE_FINGERPRINT_SCRIPT:-$(dirname "${BASH_SOURCE[0]}")/cache-fingerprint.sh}
  if [[ ! -r $script ]]; then
    warn "$script not found: cache fingerprint not uploaded (CI can't compare it)"
    return 0
  fi
  # The environment the build sees: the exports loaded, from the checkout.
  # shellcheck source=/dev/null
  if ! (export CI_CACHE_NO_REFRESH=1 && set -a && . "$env_file" && set +a && cd "$dir" && bash "$script") >"$fp" 2>/dev/null || [[ ! -s $fp ]]; then
    warn "cache-fingerprint.sh failed: cache fingerprint not uploaded"
    return 0
  fi
  # cache-fingerprint.sh already drops secrets; this guard makes sure neither credential leaves.
  if grep -qF -- "$token" "$fp" || grep -qF -- "$key" "$fp"; then
    warn "the fingerprint contained a credential: not uploaded"
    return 0
  fi
  local code
  code=$(printf 'Authorization: Bearer %s\n' "$token" | curl -sS --retry 2 -X PUT \
    -H @- -H 'content-type: text/plain; charset=utf-8' --data-binary "@$fp" \
    -o /dev/null -w '%{http_code}' "$url/v1/fingerprint" 2>/dev/null) || code=000
  if [[ $code == 204 ]]; then
    echo "ci-cache: cache fingerprint uploaded (the branch's CI compares it with its own)"
  else
    warn "uploading the cache fingerprint answered $code: CI won't compare it"
  fi
}
if [[ ${CI_CACHE_FINGERPRINT:-true} != false ]]; then upload_fingerprint || warn "fingerprint upload failed"; fi

echo "ci-cache: $tier session for branch '$branch' ($repo) until $expires"
echo "ci-cache: exports in $env_file — load them with: source $env_file"
